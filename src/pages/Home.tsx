function CiteCard() {
  const [copied, setCopied] = useState(false)
  const copy = async () => {
    try { await navigator.clipboard.writeText(CITATION); setCopied(true); setTimeout(() => setCopied(false), 2000) } catch { /* clipboard blocked */ }
  }
  return (
    <div id="cite" className="flex flex-col gap-3 rounded-md border border-rule bg-plate p-5">
      <div className="label" style={{ fontSize: 13 }}>How to cite · APA 7</div>
      <p className="m-0 text-[16.5px] leading-[1.55]" style={{ paddingLeft: '2em', textIndent: '-2em' }}>
        Waller, J. (2026). <i>HemoLab: An interactive, first-principles curriculum in hemodynamics</i> (Version 2.0) [Computer software]. Perfusia. https://perfusia.github.io/hemodynamics
      </p>
      <button type="button" className="btn self-start" onClick={copy}>{copied ? 'Copied' : 'Copy citation'}</button>
    </div>
  )
}

